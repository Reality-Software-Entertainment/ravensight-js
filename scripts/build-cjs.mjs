/**
 * Generates dist/index.cjs from src/index.js.
 *
 * There is no bundler here on purpose. src/index.js is plain JavaScript whose
 * only module syntax is `export` keywords in column zero and one trailing
 * `export default`. Stripping those and appending a CommonJS footer is enough
 * to produce a byte for byte equivalent CJS build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src', 'index.js'), 'utf8');

if (/^\s*import\s/m.test(source)) {
  throw new Error('build-cjs: src/index.js must not contain import statements');
}

const NAMED_EXPORTS = [
  'VERSION',
  'DEFAULT_API_URL',
  'MAX_BATCH_SIZE',
  'RavensightError',
  'MemoryStorage',
  'Ravensight',
  'normalizeApiUrl',
  'parseRetryAfterMs',
  'chooseUnloadTransport',
];

for (const name of NAMED_EXPORTS) {
  const pattern = new RegExp('^export (?:class|function|const) ' + name + '\\b', 'm');
  if (!pattern.test(source)) {
    throw new Error('build-cjs: expected export `' + name + '` was not found in src/index.js');
  }
}

const body = source
  .replace(/^export default .*$/gm, '')
  .replace(/^export /gm, '');

const footer = [
  '',
  '// --- CommonJS exports (generated by scripts/build-cjs.mjs) ---',
  'module.exports = Ravensight;',
  'module.exports.default = Ravensight;',
  ...NAMED_EXPORTS.map((name) => 'module.exports.' + name + ' = ' + name + ';'),
  '',
].join('\n');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'index.cjs'), body + footer, 'utf8');

console.log('built dist/index.cjs');
