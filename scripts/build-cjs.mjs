/**
 * Generates dist/index.cjs from src/index.js.
 *
 * There is no bundler here on purpose. src/index.js is plain JavaScript whose
 * only module syntax is `export` keywords in column zero and one trailing
 * `export default`. Stripping those and appending a CommonJS footer is enough
 * to produce a byte for byte equivalent CJS build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src', 'index.js'), 'utf8');

if (/^\s*import\s/m.test(source)) {
  throw new Error('build-cjs: src/index.js must not contain import statements');
}

const NAMED_EXPORTS = [
  'VERSION',
  'DEFAULT_API_URL',
  'MAX_BATCH_SIZE',
  'FEEDBACK_CATEGORIES',
  'RS_KINDS',
  'MAX_EVENT_BYTES',
  'RavensightError',
  'MemoryStorage',
  'Ravensight',
  'normalizeApiUrl',
  'parseRetryAfterMs',
  'chooseUnloadTransport',
  'MAX_PERSISTED_EVENTS',
  'GZIP_MIN_BYTES',
  'AD_FORMATS',
  'AD_RESULTS',
  'queueKeyHash',
  'signRequest',
  'signedBeaconBody',
  'eventDataBytes',
  'microsFromDecimalString',
  'microsFromRevenue',
  'adFormatFrom',
  'ERROR_CAPS',
  'scrubText',
  'SiteTracker',
  'createSiteTracker',
];

for (const name of NAMED_EXPORTS) {
  const pattern = new RegExp('^export (?:class|function|const) ' + name + '\\b', 'm');
  if (!pattern.test(source)) {
    throw new Error('build-cjs: expected export `' + name + '` was not found in src/index.js');
  }
}

const body = source
  .replace(/^export default .*$/gm, '')
  .replace(/^export /gm, '');

const footer = [
  '',
  '// --- CommonJS exports (generated by scripts/build-cjs.mjs) ---',
  'module.exports = Ravensight;',
  'module.exports.default = Ravensight;',
  ...NAMED_EXPORTS.map((name) => 'module.exports.' + name + ' = ' + name + ';'),
  '',
].join('\n');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'index.cjs'), body + footer, 'utf8');
// Small browser-only distribution, using the exact same source implementation.
// Helpers follow this repository's top-level closing-brace convention. Fail
// closed on a missing helper rather than silently emitting an incomplete asset.
function declaration(name) {
  const match = source.match(new RegExp('^(?:export )?(?:function|class) ' + name + '\\b[\\s\\S]*?^}', 'm'));
  if (!match) throw new Error('build-cjs: missing website dependency ' + name);
  return match[0];
}
const siteStart = source.indexOf('// Website mode deliberately');
if (siteStart < 0) throw new Error('build-cjs: missing website source marker');
const siteModule = [
  '// Generated from src/index.js. No external imports or automatic initialization.',
  source.match(/^export const DEFAULT_API_URL = .*$/m)[0],
  ...['utf8Bytes', 'utf8Length', 'queueKeyHash', 'randomId', 'MemoryStorage', 'normalizeApiUrl', 'parseRetryAfterMs'].map(declaration),
  source.slice(siteStart),
].join('\n\n');
writeFileSync(join(root, 'dist', 'site.js'), siteModule, 'utf8');

console.log('built dist/index.cjs and dist/site.js');
